function LogoutButton({ className = '' }: { className?: string }) {
  const navigate = useNavigate();
  const { logout } = useAuth();
  const handleLogout = () => {
    logout();
    navigate('/login');
  };
  return <button type="button" onClick={handleLogout} className={className}>Sair</button>;
}


